#!/usr/bin/env python3
"""Contrast of every pair a person reads in each dark style (WCAG 2 ratio), from the values in
Shared/DarkStyle.swift, so the numbers are always the shipped ones (OLA-221).

  python3 tools/contrast.py [out.txt]

Thresholds: body text 7:1 (AAA), secondary text and links 4.5:1 (AA), icons, status marks and
control edges 3:1. A line marked LOW is under its threshold.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = open(os.path.join(HERE, "..", "Shared", "DarkStyle.swift")).read()


def tones(name):
    m = re.search(r"static let %s = DarkTones\((.*?)\)\n" % name, SRC, re.S)
    return {k: int(v, 16) for k, v in re.findall(r"(\w+): 0x([0-9a-fA-F]{6})", m.group(1))}


def lum(h):
    def ch(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(h >> 16 & 255) + 0.7152 * ch(h >> 8 & 255) + 0.0722 * ch(h & 255)


def ratio(a, b):
    x, y = lum(a), lum(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


PAIRS = [
    # (what, foreground, background, threshold)
    ("body text on the page", "text", "page", 7),
    ("body text in a code block", "text", "code", 7),
    ("body text in the input box", "text", "field", 7),
    ("secondary text on the page", "text2", "page", 4.5),
    ("tertiary text (times, captions) on the page", "text3", "page", 4.5),
    ("links on the page", "accentText", "page", 4.5),
    ("sidebar text", "chromeText", "chrome", 7),
    ("sidebar text on the selected row", "chromeText", "chromeSelected", 7),
    ("sidebar secondary text", "chromeText2", "chrome", 4.5),
    ("sidebar tertiary text", "chromeText3", "chrome", 4.5),
    ("button label on the accent", "onAccent", "accent", 4.5),
    ("accent mark on the page (step icons, focus)", "accent", "page", 3),
    ("Ola needs you: its words on the page", "attentionText", "page", 4.5),
    ("Ola needs you: its words on its wash", "attentionText", "attentionWash", 4.5),
    ("body text on the attention wash (approval card)", "text", "attentionWash", 7),
    ("working (lamp) mark on the page", "running", "page", 3),
    ("body text on the working wash", "text", "runningWash", 7),
    ("done (green) mark on the page", "ok", "page", 3),
    ("hairline on the page (control edge)", "separatorStrong", "page", 1.0),
]


def report():
    out = ["Ola dark styles: contrast of what a person reads (WCAG 2 ratio)",
           "Generated by apps/activist-ai/apple/tools/contrast.py from Shared/DarkStyle.swift.", ""]
    for name in ("graphite", "ink"):
        t = tones(name)
        out.append(f"== {name.capitalize()}  (frame #{t['chrome']:06x}, page #{t['page']:06x}, text #{t['text']:06x}, accent #{t['accent']:06x})")
        out.append(f"   page lifted above the frame: {ratio(t['page'], t['chrome']):.2f}:1 (luminance step)")
        for what, fg, bg, need in PAIRS:
            r = ratio(t[fg], t[bg])
            flag = "" if r >= need else "   LOW"
            out.append(f"   {r:5.2f}:1  {what}  (#{t[fg]:06x} on #{t[bg]:06x}; needs {need}:1){flag}")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = report()
    print(text)
    if len(sys.argv) > 1:
        open(sys.argv[1], "w").write(text + "\n")
