#!/usr/bin/env node
// Ola's cards, described once (OLA-325): the web app's web/server/cards.mjs (with the two parsers it
// imports) as one script for JavaScriptCore, written into OlaKit as a Swift string, so the Mac and
// iPhone apps run the very same description the website runs.
//
//   node apple/tools/cards-js.mjs           writes apple/OlaKit/Sources/OlaKit/CardsJS.swift
//   node apple/tools/cards-js.mjs --check   exit 1 when that file is not what the sources make
//
// OlaKit's CardsTests also refuses a copy whose sources' fingerprint differs from the files in the
// repo, so a change to cards.mjs without this step fails `swift test`.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const SERVER = path.join(HERE, '../../web/server')
const OUT = path.join(HERE, '../OlaKit/Sources/OlaKit/CardsJS.swift')
/** In order: each may import only from the ones before it. */
export const MODULES = ['webask', 'publishask', 'cards']

export function build() {
  const parts = []
  const hash = crypto.createHash('sha256')
  for (const m of MODULES) {
    const src = fs.readFileSync(path.join(SERVER, `${m}.mjs`), 'utf8')
    hash.update(src)
    const names = [...src.matchAll(/^export (?:async )?(?:function|const|let) (\w+)/gm)].map((x) => x[1])
    let body = src.replace(/^import \{([^}]+)\} from '\.\/(\w+)\.mjs'\n/gm, (_, list, from) => {
      if (!MODULES.slice(0, MODULES.indexOf(m)).includes(from)) throw new Error(`${m}.mjs imports ${from}.mjs, which is not before it`)
      return `const {${list}} = __${from};\n`
    })
    if (/^import /m.test(body)) throw new Error(`${m}.mjs has an import JavaScriptCore cannot take`)
    body = body.replace(/^export /gm, '')
    parts.push(`const __${m} = (() => {\n${body}\nreturn { ${names.join(', ')} };\n})();`)
  }
  const js = `${parts.join('\n')}\nglobalThis.OlaCards = __cards;\n`
  if (js.includes('"""##') || js.includes('\\##(')) throw new Error('the script holds the Swift string delimiter')
  const fp = hash.digest('hex')
  return `// Generated by apple/tools/cards-js.mjs from web/server/{${MODULES.join(',')}}.mjs. Do not edit: change\n// those files and run \`node apple/tools/cards-js.mjs\` (OLA-325). CardsTests checks the fingerprint.\n\nenum CardsJS {\n  /// SHA-256 of the three sources, in order.\n  static let sourceHash = "${fp}"\n  static let script = ##"""\n${js}"""##\n}\n`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const swift = build()
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (now !== swift) {
      console.error('CardsJS.swift is not what web/server/cards.mjs makes: run node apple/tools/cards-js.mjs')
      process.exit(1)
    }
    console.log('CardsJS.swift is current')
  } else {
    fs.writeFileSync(OUT, swift)
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
  }
}
