part_loader = '''
/* optional progress hook (for the app's loading UI / remote diagnosis) */
void (*gGptProgress)(int step) = 0;
#define PROG(n) do { if (gGptProgress) gGptProgress(n); } while (0)

/* generation-time knobs & tables (v2 engine) */
int gWantLogits = 1;              /* 0 during prompt prefill: skip classifier */
static float gAttnScale = 1.0f;   /* sqrtf(head_size), hoisted out of attention */
static float *gRopeCos = 0L, *gRopeSin = 0L;   /* [seq_len][head_size/2] */

/* int8 x int8 product table (v3 speed): the 68000's MULS.W is ~50 cycles; a
 * table read is ~2x faster and BYTE-IDENTICAL (same products), so the model
 * output is unchanged. 65536 entries x int16 = 128KB, built once at init.
 * Index = ((uint8)a << 8) | (uint8)b, value = (int8)a * (int8)b. */
static int16_t *gMulLUT = 0L;
static int build_mul_lut(void) {
    int a, b;
    gMulLUT = (int16_t *)malloc(65536L * sizeof(int16_t));
    if (!gMulLUT) return -1;
    for (a = -128; a < 128; a++)
        for (b = -128; b < 128; b++)
            gMulLUT[(((long)(a & 0xFF)) << 8) | (b & 0xFF)] = (int16_t)(a * b);
    return 0;
}

static int big_endian(void) { unsigned short x = 1; return *((unsigned char *)&x) == 0; }
static uint32_t rd32(const unsigned char *p) {
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8)
         | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}
static float rdf(const unsigned char *p) {
    uint32_t u = rd32(p); float f; memcpy(&f, &u, 4); return f;
}
static void swap4(void *v) {
    unsigned char *b = (unsigned char *)v, t;
    t = b[0]; b[0] = b[3]; b[3] = t; t = b[1]; b[1] = b[2]; b[2] = t;
}
static void swapf(float *a, long n) { long i; if (!big_endian()) return; for (i = 0; i < n; i++) swap4(&a[i]); }
static void swap_scales(QuantizedTensor *qt, int n, int size_each) {
    int i; if (!big_endian()) return;
    for (i = 0; i < n; i++) swapf(qt[i].s, size_each / GS);
}

/* Precompute the RoPE rotation table once at init. The expressions are
 * copied verbatim from runq.c's per-token loop, so the table entries are
 * bit-identical to what the reference computes on the fly. Costs
 * seq_len * head_size/2 * 2 floats of RAM (256*8*2*4 = 16K at head 16). */
static int build_rope(Config *p) {
    int hs = p->dim / p->n_heads, half = hs >> 1, k;
    long pos, n = (long)p->seq_len * half;
    float *freq;
    gRopeCos = (float *)malloc(n * sizeof(float));
    gRopeSin = (float *)malloc(n * sizeof(float));
    freq = (float *)malloc((half > 0 ? half : 1) * sizeof(float));
    if (!gRopeCos || !gRopeSin || !freq) return -1;
    /* freq depends only on the head dim (hd = 2k), NOT on pos: compute the
     * expensive powf once per k (4 calls here) instead of seq_len*half. The
     * values are bit-identical to the per-token reference (hd = 2k). */
    for (k = 0; k < half; k++)
        freq[k] = 1.0f / powf(10000.0f, (2 * k) / (float)hs);
    for (pos = 0; pos < p->seq_len; pos++) {
        for (k = 0; k < half; k++) {
            float val = pos * freq[k];
            gRopeCos[pos * half + k] = cosf(val);
            gRopeSin[pos * half + k] = sinf(val);
        }
    }
    free(freq);
    return 0;
}

/* Map weights straight out of the in-RAM checkpoint buffer. Same as runq.c's
 * memory_map_weights but WITHOUT building a full dequantized token table --
 * forward() dequantizes the one needed row per step instead (saves vocab*dim
 * floats of RAM). */
static void map_weights(TransformerWeights *w, Config *p, void *ptr, int shared_classifier) {
    int head_size = p->dim / p->n_heads;
    float *fptr = (float *)ptr;
    w->rms_att_weight = fptr; fptr += p->n_layers * p->dim;
    w->rms_ffn_weight = fptr; fptr += p->n_layers * p->dim;
    w->rms_final_weight = fptr; fptr += p->dim;
    ptr = (void *)fptr;
    w->q_tokens = init_quantized_tensors(&ptr, 1, p->vocab_size * p->dim);
    w->token_embedding_table = 0L;              /* dequantized on the fly */
    w->wq = init_quantized_tensors(&ptr, p->n_layers, p->dim * (p->n_heads * head_size));
    w->wk = init_quantized_tensors(&ptr, p->n_layers, p->dim * (p->n_kv_heads * head_size));
    w->wv = init_quantized_tensors(&ptr, p->n_layers, p->dim * (p->n_kv_heads * head_size));
    w->wo = init_quantized_tensors(&ptr, p->n_layers, (p->n_heads * head_size) * p->dim);
    w->w1 = init_quantized_tensors(&ptr, p->n_layers, p->dim * p->hidden_dim);
    w->w2 = init_quantized_tensors(&ptr, p->n_layers, p->hidden_dim * p->dim);
    w->w3 = init_quantized_tensors(&ptr, p->n_layers, p->dim * p->hidden_dim);
    w->wcls = shared_classifier ? w->q_tokens
              : init_quantized_tensors(&ptr, 1, p->dim * p->vocab_size);
}

/* v2 checkpoint header: [magic u32][version i32][Config 7*i32][shared u8][GS i32]
 * padded to 256 bytes, then the weights. All scalars little-endian. */
static int load_model_mem(Transformer *t, const void *data, long len) {
    const unsigned char *b = (const unsigned char *)data;
    Config *p = &t->config;
    int cfg = (int)sizeof(Config);      /* 28 */
    uint8_t shared; int hs, L;
    if (len < 256) return -1;
    if (rd32(b) != 0x616b3432u) return -1;          /* magic "ak42" */
    if ((int)rd32(b + 4) != 2) return -1;           /* version 2 */
    p->dim        = (int)rd32(b + 8);
    p->hidden_dim = (int)rd32(b + 12);
    p->n_layers   = (int)rd32(b + 16);
    p->n_heads    = (int)rd32(b + 20);
    p->n_kv_heads = (int)rd32(b + 24);
    p->vocab_size = (int)rd32(b + 28);
    p->seq_len    = (int)rd32(b + 32);
    shared = b[8 + cfg];                             /* b[36] */
    GS = (int)rd32(b + 8 + cfg + 1);                 /* b[37..40] */
    if (GS <= 0 || (GS & 7)) return -1;              /* unrolled matmul needs GS % 8 == 0 */
    map_weights(&t->weights, p, (void *)(b + 256), shared);

    /* On big-endian (the Mac) the fp32 regions are byte-swapped in place to
     * native order. No-op on little-endian. */
    hs = p->dim / p->n_heads; L = p->n_layers;
    swapf(t->weights.rms_att_weight,   (long)L * p->dim);
    swapf(t->weights.rms_ffn_weight,   (long)L * p->dim);
    swapf(t->weights.rms_final_weight, p->dim);
    swap_scales(t->weights.q_tokens, 1, p->vocab_size * p->dim);
    swap_scales(t->weights.wq, L, p->dim * (p->n_heads * hs));
    swap_scales(t->weights.wk, L, p->dim * (p->n_kv_heads * hs));
    swap_scales(t->weights.wv, L, p->dim * (p->n_kv_heads * hs));
    swap_scales(t->weights.wo, L, (p->n_heads * hs) * p->dim);
    swap_scales(t->weights.w1, L, p->dim * p->hidden_dim);
    swap_scales(t->weights.w2, L, p->hidden_dim * p->dim);
    swap_scales(t->weights.w3, L, p->dim * p->hidden_dim);
    if (t->weights.wcls != t->weights.q_tokens)
        swap_scales(t->weights.wcls, 1, p->dim * p->vocab_size);
    return 0;
}
'''

# build_tokenizer_mem needs the Tokenizer type, so it is emitted AFTER the
# tokenizer structs (see assembly order below).
part_tokload = '''
/* Tokenizer parsed from an in-RAM buffer (was fopen/fread).
 * format: [max_token_length i32] then per token: [score f32][len i32][bytes].
 *
 * The vocab strings go in ONE block, not vocab_size separate mallocs. On the
 * 68000 Mac, ~2048 small NewPtr calls after the big KV-cache alloc thrash the
 * Memory Manager's free list (O(n^2)) -- that was ~60s of the startup. One
 * allocation makes the load near-instant. gTokBlob is freed in free_tokenizer. */
static char *gTokBlob = 0L;
static void build_tokenizer_mem(Tokenizer *t, const void *data, int vocab_size) {
    const unsigned char *b = (const unsigned char *)data;
    long off, total; int i, slen; char *dst;
    t->vocab_size = vocab_size;
    t->vocab = (char **)malloc(vocab_size * sizeof(char *));
    t->vocab_scores = (float *)malloc(vocab_size * sizeof(float));
    t->sorted_vocab = 0L;
    for (i = 0; i < 256; i++) { t->byte_pieces[i*2] = (unsigned char)i; t->byte_pieces[i*2+1] = '\\0'; }
    t->max_token_length = rd32(b);                   /* little-endian */
    /* pass 1: total bytes for all strings (+1 NUL each) */
    off = 4; total = 0;
    for (i = 0; i < vocab_size; i++) {
        off += 4;                                    /* score */
        slen = (int)rd32(b + off); off += 4;
        total += (long)slen + 1;
        off += slen;
    }
    gTokBlob = (char *)malloc(total > 0 ? total : 1);
    /* pass 2: copy each string into the blob; vocab[i] points into it */
    off = 4; dst = gTokBlob;
    for (i = 0; i < vocab_size; i++) {
        t->vocab_scores[i] = rdf(b + off); off += 4;
        slen = (int)rd32(b + off);         off += 4;
        t->vocab[i] = dst;
        memcpy(dst, b + off, slen); dst[slen] = '\\0';
        dst += slen + 1; off += slen;
    }
}
'''

