#!/usr/bin/env python3
"""Assemble gpt.c from llama2.c/runq.c (int8 quantized engine), v2.

Reuses runq.c's numeric code verbatim (quantize/dequantize/forward/tokenizer)
and swaps the Unix/CLI parts for the Mac:
  - load from an in-RAM buffer (an embedded resource) instead of mmap'ing a file
  - dequantize the token-embedding ROW on the fly in forward() instead of holding
    a full dequantized fp32 table (~500KB saved) -- important on the 4MB Plus
  - printf output -> a streaming callback; no CLI main/chat

v2 (2026-07-04) -- the 68000 speed pass. Every change below is bit-identical
to the reference numerics (same float ops, same order) EXCEPT the sampler at
temperature > 0 (top-k replaces top-p; temp 0 argmax is unchanged, which is
what the host equivalence test runs):
  1. matmul: int8 products via the gcc mulhisi3 idiom so the 68000 uses its
     native 16x16 muls.w instead of a __mulsi3 library call; inner loop
     unrolled 8x. Same products, same per-group summation order.
  2. RoPE: cos/sin precomputed once at init into tables (identical
     expressions), killing ~600 soft-float powf/cosf/sinf calls per token.
  3. attention: sqrtf(head_size) hoisted to init (gAttnScale).
  4. prefill: while processing the prompt the logits are never read, so the
     final rmsnorm + dim x vocab classifier matmul are skipped (~30%/token).
  5. sampler: top-k (k=40) with softmax over just the k survivors -- replaces
     softmax-over-vocab + qsort. temp==0 still routes to sample_argmax.
  6. GptGenerate gains a tick callback: per-position progress + abort, so the
     app can pump its event loop and cancel mid-reply.
"""
