old_sample = '''int sample(Sampler* sampler, float* logits) {
    // sample the token given the logits and some hyperparameters
    int next;
    if (sampler->temperature == 0.0f) {
        // greedy argmax sampling: take the token with the highest probability
        next = sample_argmax(logits, sampler->vocab_size);
    } else {
        // apply the temperature to the logits
        for (int q=0; q<sampler->vocab_size; q++) { logits[q] /= sampler->temperature; }
        // apply softmax to the logits to get the probabilities for next token
        softmax(logits, sampler->vocab_size);
        // flip a (float) coin (this is our source of entropy for sampling)
        float coin = random_f32(&sampler->rng_state);
        // we sample from this distribution to get the next token
        if (sampler->topp <= 0 || sampler->topp >= 1) {
            // simply sample from the predicted probability distribution
            next = sample_mult(logits, sampler->vocab_size, coin);
        } else {
            // top-p (nucleus) sampling, clamping the least likely tokens to zero
            next = sample_topp(logits, sampler->vocab_size, sampler->topp, sampler->probindex, coin);
        }
    }
    return next;
}'''
new_sample = '''#define GPT_TOPK 40

static int sample_topk(Sampler *sampler, float *logits) {
    /* top-k sampling built for the 68000: one early-out pass selects the k
     * highest logits (no softmax over the whole vocab, no qsort -- those cost
     * seconds per token in software float), then a temperature softmax over
     * just those k and one draw. */
    ProbIndex *pi = sampler->probindex;
    int n = sampler->vocab_size, k = GPT_TOPK;
    int i, j, cnt = 0, mini = 0;
    float coin, maxv, sum, r, cdf;
    if (k > n) k = n;
    for (i = 0; i < n; i++) {
        float v = logits[i];
        if (cnt < k) {
            pi[cnt].prob = v; pi[cnt].index = i;
            if (++cnt == k) {
                mini = 0;
                for (j = 1; j < k; j++) if (pi[j].prob < pi[mini].prob) mini = j;
            }
        } else if (v > pi[mini].prob) {
            pi[mini].prob = v; pi[mini].index = i;
            mini = 0;
            for (j = 1; j < k; j++) if (pi[j].prob < pi[mini].prob) mini = j;
        }
    }
    maxv = pi[0].prob;
    for (i = 1; i < cnt; i++) if (pi[i].prob > maxv) maxv = pi[i].prob;
    sum = 0.0f;
    for (i = 0; i < cnt; i++) {
        pi[i].prob = expf((pi[i].prob - maxv) / sampler->temperature);
        sum += pi[i].prob;
    }
    coin = random_f32(&sampler->rng_state);
    r = coin * sum;
    cdf = 0.0f;
    for (i = 0; i < cnt; i++) {
        cdf += pi[i].prob;
        if (r < cdf) return pi[i].index;
    }
    return pi[cnt - 1].index;
}

int sample(Sampler* sampler, float* logits) {
    if (sampler->temperature == 0.0f)
        return sample_argmax(logits, sampler->vocab_size);   /* greedy: exact */
    return sample_topk(sampler, logits);
}'''
