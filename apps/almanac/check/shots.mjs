import { chromium } from 'playwright'
// usage: node check/shots.mjs <out-dir> <base url> <passcode>  (playwright comes from hilma's root node_modules)
const [,, out, base, pass] = process.argv
const browser = await chromium.launch()
for (const [name, vp] of [['desk', { width: 1440, height: 900 }], ['phone', { width: 390, height: 844 }]]) {
  const ctx = await browser.newContext({ viewport: vp, deviceScaleFactor: 2 })
  const page = await ctx.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await page.goto(base + '/almanac/')
  await page.waitForSelector('form')
  await page.screenshot({ path: `${out}/${name}-1-signin.png` })
  await page.fill('input[name=name]', 'Bart')
  await page.fill('input[name=passcode]', pass)
  await page.click('button[type=submit]')
  await page.waitForSelector('.titlepage')
  await page.waitForSelector('table.bt', { timeout: 15000 })
  await page.screenshot({ path: `${out}/${name}-2-home.png`, fullPage: true })
  await page.click('#h-chats a')
  await page.waitForSelector('.turn .md')
  await page.waitForTimeout(1500)
  await page.screenshot({ path: `${out}/${name}-3-chat.png`, fullPage: true })
  await page.goto(base + '/almanac/#/artifacts')
  await page.waitForSelector('.gcard')
  await page.waitForTimeout(1000)
  await page.screenshot({ path: `${out}/${name}-4-gallery.png`, fullPage: true })
  await page.click('.gcard')
  await page.waitForSelector('#body')
  await page.waitForTimeout(2500)
  await page.screenshot({ path: `${out}/${name}-5-artifact.png`, fullPage: true })
  console.log(name, 'errors:', errors.length ? errors : 'none')
  await ctx.close()
}
await browser.close()
